# --------------------------------------------------------------------------
# 3. 拼装参考资料
# --------------------------------------------------------------------------
def format_context(sources: list[dict]) -> str:
    """把检索片段拼成带编号的上下文，编号要和前端展示的顺序完全一致。"""
    if not sources:
        return "（本次没有检索到任何相关资料）"

    blocks = []
    for s in sources:
        title = f"[{s['id']}] 来源：《{s['source']}》"
        if s.get("section"):
            title += f" · {s['section']}"
        blocks.append(f"{title}\n{s['content'].strip()}")
    return "\n\n".join(blocks)


